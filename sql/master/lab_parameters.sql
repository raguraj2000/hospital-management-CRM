-- ==============================================================================
-- Table: master.lab_parameters
-- Purpose: Analyte definitions, measurement methods, and standard reference intervals
-- Source: packages/shared/src/lab-catalog.ts
-- ==============================================================================

CREATE TABLE IF NOT EXISTS master.lab_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_code VARCHAR(40) NOT NULL REFERENCES master.lab_catalog(code) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    method VARCHAR(120) NOT NULL DEFAULT '',
    unit VARCHAR(40) NOT NULL DEFAULT '',
    ref_range VARCHAR(120) NOT NULL DEFAULT '',
    value_type VARCHAR(20) NOT NULL DEFAULT 'number' CHECK (value_type IN ('number', 'text')),
    options JSONB NULL,           -- E.g. ["Negative", "Positive", "Reactive"]
    no_flag BOOLEAN NOT NULL DEFAULT false,
    optional BOOLEAN NOT NULL DEFAULT false,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS ix_master_lab_params ON master.lab_parameters (test_code, sort_order);
COMMENT ON TABLE master.lab_parameters IS 'Reference analyte metrics and normal biological intervals for standardized lab tests';
