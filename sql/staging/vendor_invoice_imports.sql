-- ==============================================================================
-- Table: staging.vendor_invoice_imports
-- Purpose: Inward distributor invoice spreadsheet headers
-- Source: packages/shared/src/purchase-import.ts
-- ==============================================================================

CREATE TABLE IF NOT EXISTS staging.vendor_invoice_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    vendor_id BIGINT NOT NULL REFERENCES public.vendors(id) ON DELETE RESTRICT,
    vendor_bill_no VARCHAR(60) NOT NULL,
    bill_date DATE NOT NULL,
    total_rows INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'VALIDATED', 'POSTED', 'REJECTED')),
    uploaded_by BIGINT NOT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE staging.vendor_invoice_imports IS 'Staging headers for bulk supplier invoice spreadsheet imports';
