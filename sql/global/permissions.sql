-- ==============================================================================
-- Table: global.permissions
-- Purpose: Granular platform authorization privileges categorized by module and action
-- Source: packages/shared/src/index.ts (ALL_PERMISSIONS), db-design.md Section 8
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(80) NOT NULL UNIQUE, -- E.g. 'patient.read', 'billing.invoice.create'
    module VARCHAR(40) NOT NULL,     -- E.g. 'patient', 'op_visit', 'billing', 'pharmacy', 'lab', 'inventory'
    resource VARCHAR(40) NOT NULL,   -- E.g. 'patient', 'invoice', 'batch', 'order'
    action VARCHAR(40) NOT NULL,     -- E.g. 'read', 'create', 'update', 'delete', 'dispense', 'cancel'
    name VARCHAR(120) NOT NULL,      -- Human-readable label
    description TEXT NULL,
    is_system BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_permissions_module ON global.permissions (module, resource);
COMMENT ON TABLE global.permissions IS 'System-wide catalog of all atomic privileges and functional entitlements';
