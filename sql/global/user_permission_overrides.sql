-- ==============================================================================
-- Table: global.user_permission_overrides
-- Purpose: User-specific explicit grant or deny overrides with deterministic precedence
-- Source: db-design.md Section 8 (User-specific permission overrides)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.user_permission_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES global.users(id) ON DELETE CASCADE,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES global.permissions(id) ON DELETE CASCADE,

    -- Resource scope of override (null implies company-wide)
    branch_id BIGINT NULL,
    region_id BIGINT NULL,
    inventory_id BIGINT NULL,

    is_granted BOOLEAN NOT NULL, -- TRUE = Explicit Grant (Allow), FALSE = Explicit Deny (Deny overrides Role)
    reason TEXT NOT NULL,        -- Mandatory clinical or administrative justification
    granted_by BIGINT NOT NULL REFERENCES global.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_user_perm_overrides ON global.user_permission_overrides (user_id, company_id, permission_id);

-- Explicit hierarchical composite indexes requested for regional and inventory scoping
CREATE INDEX IF NOT EXISTS ix_user_perm_overrides_company_region 
    ON global.user_permission_overrides (company_id, region_id);

CREATE INDEX IF NOT EXISTS ix_user_perm_overrides_company_region_inventory 
    ON global.user_permission_overrides (company_id, region_id, inventory_id);

COMMENT ON TABLE global.user_permission_overrides IS 'Explicit user-level permission grants and denials. Explicit deny always supersedes role grants';
