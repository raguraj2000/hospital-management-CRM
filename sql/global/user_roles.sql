-- ==============================================================================
-- Table: global.user_roles
-- Purpose: Assigns roles to users with explicit hierarchical resource scoping
-- Source: db-design.md Section 8 (User-wise Authorization)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES global.users(id) ON DELETE CASCADE,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES global.roles(id) ON DELETE RESTRICT,
    
    -- Hierarchical resource scope (null implies company-wide scope)
    branch_id BIGINT NULL,       -- Operational facility scope
    region_id BIGINT NULL,       -- Regional territorial scope
    inventory_id BIGINT NULL,    -- Specific warehouse or dispensary scope

    is_active BOOLEAN NOT NULL DEFAULT true,
    assigned_by BIGINT NULL REFERENCES global.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_user_roles_lookup ON global.user_roles (user_id, company_id, is_active);
CREATE INDEX IF NOT EXISTS ix_user_roles_scope ON global.user_roles (company_id, branch_id, region_id, inventory_id);

-- Explicit hierarchical composite indexes requested for regional and inventory scoping
CREATE INDEX IF NOT EXISTS ix_user_roles_company_region 
    ON global.user_roles (company_id, region_id);

CREATE INDEX IF NOT EXISTS ix_user_roles_company_region_inventory 
    ON global.user_roles (company_id, region_id, inventory_id);

COMMENT ON TABLE global.user_roles IS 'Scoped role assignments permitting fine-grained access control per facility, region, or inventory';
