-- ==============================================================================
-- Table: global.organization_memberships
-- Purpose: Enrolls a user as a member of a tenant organization
-- Source: packages/core/src/db/schema.ts (user.organizationId normalized for multi-tenant users)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.organization_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES global.users(id) ON DELETE CASCADE,
    is_owner BOOLEAN NOT NULL DEFAULT false, -- Hospital owner entitlement within this organization
    is_active BOOLEAN NOT NULL DEFAULT true,  -- Revoking terminates access to this organization immediately
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ NULL,

    CONSTRAINT uq_org_membership UNIQUE (company_id, user_id)
);

CREATE INDEX IF NOT EXISTS ix_org_membership_user ON global.organization_memberships (user_id, company_id) WHERE is_active = true;
COMMENT ON TABLE global.organization_memberships IS 'Association of a user with a tenant organization. Allows one user to belong to multiple clinics';
