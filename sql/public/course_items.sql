-- ==============================================================================
-- Table: public.course_items
-- Purpose: Specific medicines, diagnostics, or procedures scheduled for a sitting
-- Source: apps/api/src/db/schema.ts (course_item)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.course_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    sitting_id BIGINT NOT NULL REFERENCES public.course_sittings(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('medicine', 'test', 'charge', 'note')),
    medicine_id BIGINT NULL, -- Deferred FK to public.medicines(id)
    test_id BIGINT NULL,     -- Deferred FK to public.lab_tests(id)
    description VARCHAR(200) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    price_paise BIGINT NOT NULL DEFAULT 0 CHECK (price_paise >= 0),
    prepaid BOOLEAN NOT NULL DEFAULT false, -- True if collected on Day 1
    given_at TIMESTAMPTZ NULL,
    given_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_course_items_sitting ON public.course_items (sitting_id, sort_order);
COMMENT ON TABLE public.course_items IS 'Line items scheduled for administration during a course sitting';
