-- ==============================================================================
-- Table: public.branches
-- Purpose: Physical healthcare facility, clinic, or operational hospital branch
-- Source: packages/core/src/db/schema.ts (branch)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    region_id BIGINT NULL REFERENCES public.regions(id) ON DELETE SET NULL,
    primary_inventory_id BIGINT NULL REFERENCES public.inventory_locations(id) ON DELETE SET NULL,
    slug VARCHAR(40) NOT NULL,                   -- URL identifier (e.g. 'main', 'north-clinic')
    name VARCHAR(150) NOT NULL,                  -- Facility display name
    code_prefix VARCHAR(10) NOT NULL,            -- Branch sequence prefix (e.g. 'MAIN')
    gstin VARCHAR(15) NULL,                      -- 15-character GSTIN if branch has separate GST registration
    state_code VARCHAR(10) NULL REFERENCES master.states(code), -- For Place of Supply resolution
    address TEXT NULL,
    phone VARCHAR(40) NULL,
    print_header JSONB NULL,                     -- Title, logo Base64, signatures, watermark
    allowed_networks TEXT NULL,                  -- CIDR network lock whitelist
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_branch_slug UNIQUE (company_id, slug),
    CONSTRAINT uq_branch_org_id UNIQUE (id, company_id),
    CONSTRAINT chk_branch_slug_format CHECK (slug ~ '^[a-z0-9-]+$'),
    CONSTRAINT chk_branch_gstin CHECK (gstin IS NULL OR gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$')
);

CREATE INDEX IF NOT EXISTS ix_branches_org_active ON public.branches (company_id) WHERE is_active = true;

-- Explicit hierarchical composite index requested for regional scoping
CREATE INDEX IF NOT EXISTS ix_branches_company_region 
    ON public.branches (company_id, region_id);

COMMENT ON TABLE public.branches IS 'Physical clinic facility operating outpatient care, local pharmacy, and billing';
