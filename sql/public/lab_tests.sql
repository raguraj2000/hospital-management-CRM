-- Source: apps/api/src/db/schema.ts (lab_test), FR-LAB-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    master_code VARCHAR(40) NULL REFERENCES master.lab_catalog(code),
    name VARCHAR(150) NOT NULL,
    price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
    department VARCHAR(80) NOT NULL DEFAULT 'OTHER TESTS',
    kind VARCHAR(20) NOT NULL DEFAULT 'panel' CHECK (kind IN ('panel', 'card')),
    hsn_sac_code VARCHAR(15) NULL REFERENCES master.hsn_sac_codes(code),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_lab_tests_branch ON public.lab_tests (branch_id, lower(name)) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.lab_tests IS 'Diagnostic test catalog configured for a clinic facility';
