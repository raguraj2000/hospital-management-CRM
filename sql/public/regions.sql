-- ==============================================================================
-- Table: public.regions
-- Purpose: Territorial or administrative regional divisions within an organization
-- Source: db-design.md Section 6 (Client Onboarding & Organization Hierarchy)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.regions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_region_org_code UNIQUE (company_id, code),
    CONSTRAINT uq_region_org_id UNIQUE (id, company_id) -- Enables composite foreign keys
);

CREATE INDEX IF NOT EXISTS ix_regions_org ON public.regions (company_id) WHERE is_active = true;
COMMENT ON TABLE public.regions IS 'Geographic or operational regions owned by an organization';
