-- ==============================================================================
-- Table: public.visit_instructions
-- Purpose: Checklist of clinical non-pharma instructions on a visit, ticked when executed
-- Source: apps/api/src/db/schema.ts (visit_instruction)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.visit_instructions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    bookmark_name VARCHAR(120) NULL,
    done_at TIMESTAMPTZ NULL,
    done_by BIGINT NULL REFERENCES global.users(id),
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_visit_instructions ON public.visit_instructions (visit_id) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.visit_instructions IS 'Clinical care checklist for a visit, tracked with completion timestamps';
