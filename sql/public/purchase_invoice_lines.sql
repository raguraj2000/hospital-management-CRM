-- ==============================================================================
-- Table: public.purchase_invoice_lines
-- Purpose: Line items on a vendor purchase invoice detailing medicines, pack sizes, and GST
-- Source: apps/api/src/db/schema.ts (purchase_line), FR-PHM-03
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.purchase_invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_invoice_id BIGINT NOT NULL REFERENCES public.purchase_invoices(id) ON DELETE CASCADE,
    medicine_id BIGINT NOT NULL REFERENCES public.medicines(id) ON DELETE RESTRICT,
    batch_id BIGINT NOT NULL REFERENCES public.inventory_batches(id) ON DELETE RESTRICT,
    hsn_code VARCHAR(15) NOT NULL REFERENCES master.hsn_sac_codes(code),
    
    -- Commercial terms from vendor bill
    pack_size INTEGER NOT NULL DEFAULT 1 CHECK (pack_size > 0),
    pack_qty INTEGER NOT NULL CHECK (pack_qty > 0),
    free_qty INTEGER NOT NULL DEFAULT 0 CHECK (free_qty >= 0),
    total_loose_units INTEGER NOT NULL CHECK (total_loose_units > 0),
    
    rate_per_pack_paise BIGINT NOT NULL CHECK (rate_per_pack_paise >= 0),
    effective_unit_cost_paise BIGINT NOT NULL CHECK (effective_unit_cost_paise >= 0),
    mrp_paise BIGINT NULL CHECK (mrp_paise IS NULL OR mrp_paise >= 0),
    
    taxable_amount_paise BIGINT NOT NULL CHECK (taxable_amount_paise >= 0),
    gst_tax_code VARCHAR(20) NOT NULL REFERENCES master.gst_tax_codes(code),
    gst_percent NUMERIC(5,2) NOT NULL CHECK (gst_percent >= 0),
    total_tax_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_tax_paise >= 0),
    line_total_paise BIGINT NOT NULL CHECK (line_total_paise >= 0)
);

CREATE INDEX IF NOT EXISTS ix_purchase_lines_bill ON public.purchase_invoice_lines (purchase_invoice_id);
COMMENT ON TABLE public.purchase_invoice_lines IS 'Itemized lines of a supplier purchase invoice with pack multipliers and free items';
