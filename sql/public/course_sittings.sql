-- ==============================================================================
-- Table: public.course_sittings
-- Purpose: Individual planned clinical encounter sessions of a multi-day course
-- Source: apps/api/src/db/schema.ts (course_sitting), FR-CRS-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.course_sittings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    course_id BIGINT NOT NULL REFERENCES public.treatment_courses(id) ON DELETE CASCADE,
    due_at TIMESTAMPTZ NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('nurse', 'review', 'lab')),
    review_fee_paise BIGINT NULL CHECK (review_fee_paise IS NULL OR review_fee_paise >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'planned' 
        CHECK (status IN ('planned', 'started', 'done', 'missed', 'cancelled')),
    visit_id BIGINT NULL REFERENCES public.op_visits(id), -- Created encounter visit
    done_at TIMESTAMPTZ NULL,
    note TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_course_sittings_due ON public.course_sittings (branch_id, due_at, status);
COMMENT ON TABLE public.course_sittings IS 'Specific scheduled clinical sittings within an ongoing treatment course';
