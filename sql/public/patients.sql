-- ==============================================================================
-- Table: public.patients
-- Purpose: Master clinical patient registry
-- Source: apps/api/src/db/schema.ts (patient), FR-PAT-01, FR-PAT-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    uhid VARCHAR(30) NOT NULL,                  -- Unique Health ID across organization (e.g. 'AH000042')
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NULL,                     -- Normalized +91 mobile
    email VARCHAR(150) NULL,
    gender VARCHAR(20) NULL CHECK (gender IN ('female', 'male', 'female child', 'male child', 'other')),
    dob DATE NULL,                              -- Accurate birth date
    age_years INTEGER NULL CHECK (age_years >= 0 AND age_years <= 130),
    blood_group VARCHAR(10) NULL,
    weight_kg NUMERIC(5,2) NULL CHECK (weight_kg > 0 AND weight_kg <= 500),
    height_cm NUMERIC(5,2) NULL CHECK (height_cm > 0 AND height_cm <= 300),
    address TEXT NULL,
    conditions TEXT NULL,                       -- Chronic conditions (e.g., 'Diabetes, Hypertension')
    emergency_contact_name VARCHAR(150) NULL,
    emergency_contact_phone VARCHAR(20) NULL,
    deactivated_at TIMESTAMPTZ NULL,
    deactivated_reason TEXT NULL,
    deactivated_by BIGINT NULL REFERENCES global.users(id),
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,

    CONSTRAINT uq_patient_org_uhid UNIQUE (company_id, uhid)
);

CREATE INDEX IF NOT EXISTS ix_patients_name ON public.patients (branch_id, lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_patients_phone ON public.patients (branch_id, phone) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.patients IS 'Master clinical patient records. UHID is unique across the entire organization';
