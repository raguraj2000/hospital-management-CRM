CREATE TABLE IF NOT EXISTS public.medicines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    form VARCHAR(30) NOT NULL REFERENCES master.uom_codes(code),
    strength VARCHAR(50) NULL,
    price_paise BIGINT NOT NULL CHECK (price_paise >= 0), -- Retail price per single loose unit
    reorder_level INTEGER NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
    hsn_code VARCHAR(15) NULL REFERENCES master.hsn_sac_codes(code) DEFAULT '3004',
    gst_tax_code VARCHAR(20) NOT NULL REFERENCES master.gst_tax_codes(code) DEFAULT 'GST_12',
    default_dose VARCHAR(40) NULL,
    default_instructions TEXT NULL,
    default_days INTEGER NULL CHECK (default_days IS NULL OR default_days > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_medicines_name ON public.medicines (branch_id, lower(name)) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.medicines IS 'Master clinic formulary items with pricing, formulation, and reorder levels';
