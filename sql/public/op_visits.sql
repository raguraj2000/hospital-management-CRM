-- ==============================================================================
-- Table: public.op_visits
-- Purpose: Outpatient clinical encounters, daily queue tokens, vitals, and notes
-- Source: apps/api/src/db/schema.ts (op_visit), FR-OP-01, FR-OP-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.op_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE RESTRICT,
    op_no VARCHAR(40) NOT NULL,                 -- Identifier (e.g. 'OP-261024-001', 'LAB-261024-001')
    visit_date DATE NOT NULL,                   -- Calendar date in IST
    status VARCHAR(20) NOT NULL DEFAULT 'waiting' 
        CHECK (status IN ('waiting', 'with_doctor', 'at_lab', 'at_counter', 'completed', 'cancelled')),
    doctor_user_id BIGINT NULL REFERENCES global.users(id) ON DELETE SET NULL,
    complaint TEXT NULL,                        -- Presenting symptoms
    referred_by VARCHAR(150) NULL,              -- External referring physician
    notes TEXT NULL,                            -- Doctor clinical findings
    pharmacy_note TEXT NULL,                    -- Clinical advice to dispensary
    lab_note TEXT NULL,                         -- Instructions to lab tech
    consultation_fee_paise BIGINT NULL CHECK (consultation_fee_paise >= 0),
    
    -- Objective clinical vitals
    bp_systolic INTEGER NULL CHECK (bp_systolic BETWEEN 30 AND 300),
    bp_diastolic INTEGER NULL CHECK (bp_diastolic BETWEEN 20 AND 200),
    pulse INTEGER NULL CHECK (pulse BETWEEN 20 AND 300),
    temperature_f NUMERIC(4,1) NULL CHECK (temperature_f BETWEEN 80.0 AND 115.0),
    spo2 INTEGER NULL CHECK (spo2 BETWEEN 40 AND 100),
    weight_kg NUMERIC(5,2) NULL CHECK (weight_kg > 0),
    height_cm NUMERIC(5,2) NULL CHECK (height_cm > 0),
    
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,

    CONSTRAINT uq_op_visit_branch_no UNIQUE (branch_id, op_no)
);

CREATE INDEX IF NOT EXISTS ix_op_visits_queue ON public.op_visits (branch_id, visit_date, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_op_visits_patient ON public.op_visits (branch_id, patient_id);
CREATE INDEX IF NOT EXISTS ix_op_visits_doctor ON public.op_visits (branch_id, doctor_user_id, visit_date);
COMMENT ON TABLE public.op_visits IS 'Outpatient clinical consultations and daily queue records';
