-- Table: public.audit_logs
-- Purpose: Regulatory, clinical, and financial immutable audit trail
-- Source: packages/core/src/db/schema.ts (audit_log), db-design.md Section 10
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    user_id BIGINT NULL REFERENCES global.users(id) ON DELETE SET NULL,
    action VARCHAR(60) NOT NULL,  -- E.g. 'create', 'update', 'delete', 'dispense', 'amend_lab', 'collect_payment'
    entity VARCHAR(60) NOT NULL,  -- E.g. 'patient', 'op_visit', 'invoice', 'prescription_item'
    entity_id VARCHAR(60) NULL,   -- Target primary key
    detail JSONB NULL,            -- Contextual payload, previous vs new values
    client_ip INET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_audit_branch_time ON public.audit_logs (branch_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_audit_entity ON public.audit_logs (entity, entity_id);
COMMENT ON TABLE public.audit_logs IS 'Immutable compliance audit trail tracking all state mutations across the system';
