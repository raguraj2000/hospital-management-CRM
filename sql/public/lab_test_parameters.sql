-- Purpose: Analytes measured within a facility diagnostic test
-- Source: apps/api/src/db/schema.ts (lab_test_parameter), FR-LAB-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_test_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    test_id BIGINT NOT NULL REFERENCES public.lab_tests(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    method VARCHAR(120) NOT NULL DEFAULT '',
    unit VARCHAR(40) NOT NULL DEFAULT '',
    ref_range VARCHAR(120) NOT NULL DEFAULT '',
    value_type VARCHAR(20) NOT NULL DEFAULT 'number' CHECK (value_type IN ('number', 'text')),
    options JSONB NULL,
    no_flag BOOLEAN NOT NULL DEFAULT false,
    optional BOOLEAN NOT NULL DEFAULT false,
    sort_order INTEGER NOT NULL DEFAULT 0,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_lab_test_params ON public.lab_test_parameters (test_id, sort_order) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.lab_test_parameters IS 'Specific analyte measurements and biological reference ranges for facility lab tests';
