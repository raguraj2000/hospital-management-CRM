-- ==============================================================================
-- Table: public.vendors
-- Purpose: Pharmaceutical distributors, consumable suppliers, and service providers
-- Source: apps/api/src/db/schema.ts (vendor), db-design.md Section 9
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NULL,
    address TEXT NULL,
    gstin VARCHAR(15) NULL, -- Supplier 15-digit GSTIN
    state_code VARCHAR(10) NULL REFERENCES master.states(code),
    credit_days INTEGER NOT NULL DEFAULT 0 CHECK (credit_days >= 0),
    notes TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,

    CONSTRAINT chk_vendor_gstin CHECK (gstin IS NULL OR gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$')
);

CREATE INDEX IF NOT EXISTS ix_vendors_branch ON public.vendors (branch_id, lower(name)) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.vendors IS 'Commercial distributors and suppliers with GSTIN registrations';
