-- ==============================================================================
-- Table: public.treatment_bookmarks
-- Purpose: Pre-configured clinical treatment protocol templates (e.g. 'Dengue Adult Protocol')
-- Source: apps/api/src/db/schema.ts (treatment_bookmark), FR-CRS-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.treatment_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_bookmarks_branch ON public.treatment_bookmarks (branch_id, lower(name)) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.treatment_bookmarks IS 'Ready-made treatment order sets applied in one click to outpatient visits';
