-- ==============================================================================
-- Table: public.inventory_batches
-- Purpose: Physical pharmaceutical inventory stock batches for FEFO tracking
-- Source: apps/api/src/db/schema.ts (medicine_batch), FR-PHM-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.inventory_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    inventory_id BIGINT NOT NULL REFERENCES public.inventory_locations(id) ON DELETE RESTRICT,
    medicine_id BIGINT NOT NULL REFERENCES public.medicines(id) ON DELETE RESTRICT,
    batch_no VARCHAR(50) NOT NULL,
    expiry_date DATE NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity >= 0), -- Loose units remaining on shelf
    received_qty INTEGER NOT NULL CHECK (received_qty > 0),
    unit_cost_paise BIGINT NOT NULL DEFAULT 0 CHECK (unit_cost_paise >= 0),
    mrp_paise BIGINT NULL CHECK (mrp_paise IS NULL OR mrp_paise >= 0),
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_inv_batch_location UNIQUE (inventory_id, medicine_id, batch_no, expiry_date)
);

CREATE INDEX IF NOT EXISTS ix_batches_fefo ON public.inventory_batches (inventory_id, medicine_id, expiry_date, quantity) WHERE quantity > 0;
COMMENT ON TABLE public.inventory_batches IS 'Physical pharmaceutical inventory batches tracked with First-Expiry-First-Out ordering';
