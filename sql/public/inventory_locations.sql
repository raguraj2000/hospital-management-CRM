-- ==============================================================================
-- Table: public.inventory_locations
-- Purpose: Distinct physical or logical stock locations (Central Warehouse, Dispensary, Sub-stores)
-- Source: db-design.md Section 6 (Organization Hierarchy & Inventory)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.inventory_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL, -- E.g. 'Central Pharmacy Warehouse', 'Emergency Floor Stock'
    type VARCHAR(40) NOT NULL DEFAULT 'pharmacy' CHECK (type IN ('warehouse', 'pharmacy', 'sub_store', 'emergency_kit', 'lab_store')),
    address TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_inventory_org_code UNIQUE (company_id, code),
    CONSTRAINT uq_inventory_org_id UNIQUE (id, company_id) -- Enables composite foreign keys
);

CREATE INDEX IF NOT EXISTS ix_inventory_loc_org ON public.inventory_locations (company_id, type);
COMMENT ON TABLE public.inventory_locations IS 'Stock holding locations. Owned directly by the organization and shared across regions';
