-- ==============================================================================
-- Table: public.credit_debit_notes
-- Purpose: Statutory GST Credit Notes and Debit Notes for returns, refunds, or reversals
-- Source: db-design.md Section 9 (Financial Immutability and Auditing)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.credit_debit_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    original_invoice_id BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    note_no VARCHAR(50) NOT NULL, -- E.g. 'CN-261024-001'
    note_type VARCHAR(10) NOT NULL CHECK (note_type IN ('CREDIT', 'DEBIT')),
    note_date DATE NOT NULL,
    reason TEXT NOT NULL,
    taxable_adjustment_paise BIGINT NOT NULL,
    tax_adjustment_paise BIGINT NOT NULL,
    total_adjustment_paise BIGINT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_credit_note_no UNIQUE (branch_id, note_no)
);

CREATE INDEX IF NOT EXISTS ix_notes_invoice ON public.credit_debit_notes (original_invoice_id);
COMMENT ON TABLE public.credit_debit_notes IS 'Formal GST credit and debit notes for invoice adjustments without mutating original records';
