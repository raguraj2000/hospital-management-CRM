-- ==============================================================================
-- Table: public.invoices
-- Purpose: Master customer/patient sales invoice supporting statutory GST and auditing
-- Source: apps/api/src/db/schema.ts (op_bill), db-design.md Section 9
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    invoice_no VARCHAR(50) NOT NULL, -- Sequential branch invoice code (e.g. 'BL-261024-001')
    visit_id BIGINT NULL REFERENCES public.op_visits(id) ON DELETE SET NULL,
    patient_id BIGINT NULL REFERENCES public.patients(id) ON DELETE RESTRICT,
    
    -- Snapshot fields protecting historical tax auditability
    patient_name_snapshot VARCHAR(150) NOT NULL,
    patient_gstin VARCHAR(15) NULL, -- Optional B2B recipient GSTIN
    seller_gstin_snapshot VARCHAR(15) NULL,
    seller_state_code VARCHAR(10) NOT NULL REFERENCES master.states(code),
    place_of_supply_state_code VARCHAR(10) NOT NULL REFERENCES master.states(code),
    is_inter_state BOOLEAN NOT NULL DEFAULT false, -- True if seller != place of supply (IGST applied)
    
    invoice_date DATE NOT NULL,
    taxable_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (taxable_amount_paise >= 0),
    cgst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (cgst_amount_paise >= 0),
    sgst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (sgst_amount_paise >= 0),
    igst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (igst_amount_paise >= 0),
    cess_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (cess_amount_paise >= 0),
    total_tax_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_tax_paise >= 0),
    discount_paise BIGINT NOT NULL DEFAULT 0 CHECK (discount_paise >= 0),
    round_off_paise INTEGER NOT NULL DEFAULT 0,
    grand_total_paise BIGINT NOT NULL CHECK (grand_total_paise >= 0),
    paid_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount_paise >= 0),
    balance_due_paise BIGINT NOT NULL DEFAULT 0 CHECK (balance_due_paise >= 0),
    
    status VARCHAR(20) NOT NULL DEFAULT 'draft' 
        CHECK (status IN ('draft', 'posted', 'part_paid', 'paid', 'cancelled', 'refunded')),
    is_immutable BOOLEAN NOT NULL DEFAULT false, -- Locked once payment is recorded or invoice is posted
    
    created_by BIGINT NULL REFERENCES global.users(id),
    posted_by BIGINT NULL REFERENCES global.users(id),
    cancelled_by BIGINT NULL REFERENCES global.users(id),
    cancel_reason TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_invoice_branch_no UNIQUE (branch_id, invoice_no)
);

CREATE INDEX IF NOT EXISTS ix_invoices_patient ON public.invoices (patient_id, invoice_date DESC);
CREATE INDEX IF NOT EXISTS ix_invoices_branch_day ON public.invoices (branch_id, invoice_date DESC);
CREATE INDEX IF NOT EXISTS ix_invoices_balance ON public.invoices (branch_id, balance_due_paise) WHERE balance_due_paise > 0;
COMMENT ON TABLE public.invoices IS 'Unified patient billing and tax invoices covering consultations, diagnostics, procedures, and drugs';
