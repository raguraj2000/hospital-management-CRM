-- ==============================================================================
-- Table: public.course_templates
-- Purpose: Reusable course master protocol templates
-- Source: apps/api/src/db/schema.ts (course_template)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.course_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    sittings JSONB NOT NULL, -- Template structure of days, times, and items
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

COMMENT ON TABLE public.course_templates IS 'Pre-configured treatment course templates instantiated for patients';
