-- ==============================================================================
-- Table: public.treatment_bookmark_lines
-- Purpose: Itemized medicines and nurse instructions in a treatment bookmark
-- Source: apps/api/src/db/schema.ts (treatment_bookmark_line)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.treatment_bookmark_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    bookmark_id BIGINT NOT NULL REFERENCES public.treatment_bookmarks(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('medicine', 'instruction')),
    medicine_id BIGINT NULL, -- Deferred FK to public.medicines(id)
    dose VARCHAR(40) NULL,
    days INTEGER NULL CHECK (days IS NULL OR days > 0),
    quantity INTEGER NULL CHECK (quantity IS NULL OR quantity > 0),
    instructions TEXT NULL,
    given_here BOOLEAN NOT NULL DEFAULT false,
    text TEXT NULL,          -- Used when kind = 'instruction'
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS ix_bookmark_lines ON public.treatment_bookmark_lines (bookmark_id, sort_order);
COMMENT ON TABLE public.treatment_bookmark_lines IS 'Lines belonging to a clinical bookmark order set';
