-- ==============================================================================
-- Table: public.purchase_invoice_tax_lines
-- Purpose: Immutable line-level tax component breakdown for vendor purchases
-- Source: db-design.md Section 9 (Purchase Billing GST Snapshot)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.purchase_invoice_tax_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_line_id BIGINT NOT NULL REFERENCES public.purchase_invoice_lines(id) ON DELETE CASCADE,
    tax_component VARCHAR(10) NOT NULL CHECK (tax_component IN ('CGST', 'SGST', 'UTGST', 'IGST', 'CESS')),
    rate_percent NUMERIC(5,2) NOT NULL CHECK (rate_percent >= 0),
    tax_amount_paise BIGINT NOT NULL CHECK (tax_amount_paise >= 0)
);

CREATE INDEX IF NOT EXISTS ix_purchase_tax_lines ON public.purchase_invoice_tax_lines (purchase_line_id);
COMMENT ON TABLE public.purchase_invoice_tax_lines IS 'Immutable tax snapshots capturing CGST, SGST, IGST components for purchase lines';
