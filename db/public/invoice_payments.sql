-- ==============================================================================
-- Table: public.invoice_payments
-- Purpose: Receipts recording payment collections against patient invoices
-- Source: apps/api/src/db/schema.ts (bill_payment), FR-BIL-03
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.invoice_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    invoice_id BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    receipt_no VARCHAR(60) NOT NULL, -- E.g. 'BL-261024-001/R1'
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    mode VARCHAR(20) NOT NULL REFERENCES master.payment_methods(code),
    reference VARCHAR(80) NULL,      -- Transaction reference, UPI UTR, or card auth code
    received_by BIGINT NOT NULL REFERENCES global.users(id),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_inv_payments_invoice ON public.invoice_payments (invoice_id);
CREATE INDEX IF NOT EXISTS ix_inv_payments_day ON public.invoice_payments (branch_id, received_at DESC);
COMMENT ON TABLE public.invoice_payments IS 'Append-only payment receipts collected at cashier or checkout terminals';
