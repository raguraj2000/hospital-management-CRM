-- Table: public.lab_results
-- Purpose: Verified numerical or qualitative diagnostic results with abnormal flags
-- Source: apps/api/src/db/schema.ts (lab_result), FR-LAB-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    order_id BIGINT NOT NULL REFERENCES public.lab_orders(id) ON DELETE CASCADE,
    parameter_id BIGINT NOT NULL REFERENCES public.lab_test_parameters(id) ON DELETE RESTRICT,
    value VARCHAR(150) NOT NULL,
    flag VARCHAR(5) NOT NULL DEFAULT '' CHECK (flag IN ('', 'H', 'L', '!')),
    entered_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_lab_order_param UNIQUE (order_id, parameter_id)
);

COMMENT ON TABLE public.lab_results IS 'Analyte test values recorded by technician with automated panic flagging';
