-- ==============================================================================
-- Table: public.invoice_lines
-- Purpose: Itemized lines on a patient invoice with HSN/SAC, discounts, and GST breakdown
-- Source: apps/api/src/db/schema.ts (op_bill_line), db-design.md Section 9
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
    line_type VARCHAR(30) NOT NULL CHECK (line_type IN ('CONSULTATION', 'LAB_TEST', 'PROCEDURE_CHARGE', 'MEDICINE', 'ROOM_RENT', 'OTHER')),
    reference_id BIGINT NULL, -- Target lab_order_id, prescription_item_id, or visit_charge_id
    description VARCHAR(200) NOT NULL,
    hsn_sac_code VARCHAR(15) NOT NULL REFERENCES master.hsn_sac_codes(code),
    quantity NUMERIC(10,2) NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price_paise BIGINT NOT NULL CHECK (unit_price_paise >= 0),
    gross_amount_paise BIGINT NOT NULL CHECK (gross_amount_paise >= 0),
    discount_paise BIGINT NOT NULL DEFAULT 0 CHECK (discount_paise >= 0),
    taxable_value_paise BIGINT NOT NULL CHECK (taxable_value_paise >= 0),
    gst_tax_code VARCHAR(20) NOT NULL REFERENCES master.gst_tax_codes(code),
    gst_rate_percent NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (gst_rate_percent >= 0),
    total_tax_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_tax_paise >= 0),
    net_line_amount_paise BIGINT NOT NULL CHECK (net_line_amount_paise >= 0)
);

CREATE INDEX IF NOT EXISTS ix_invoice_lines_inv ON public.invoice_lines (invoice_id);
COMMENT ON TABLE public.invoice_lines IS 'Itemized patient service and product charges on an invoice';
