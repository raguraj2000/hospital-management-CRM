-- ==============================================================================
-- Table: public.prescription_items
-- Purpose: Prescribed pharmaceutical line items linked to an OP consultation
-- Source: apps/api/src/db/schema.ts (prescription_item), FR-RX-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    medicine_id BIGINT NOT NULL, -- Deferred FK to public.medicines(id)
    dose VARCHAR(40) NOT NULL,   -- Frequency pattern (e.g. '1-0-1', '1-1-1-1')
    days INTEGER NOT NULL CHECK (days > 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    instructions TEXT NULL,
    given_here BOOLEAN NOT NULL DEFAULT false, -- If true, administered by clinic nurse
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'dispensed', 'declined')),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_rx_items_visit ON public.prescription_items (visit_id, status);
COMMENT ON TABLE public.prescription_items IS 'Prescribed medicines linked to outpatient visits with dosing instructions and dispensing state';
