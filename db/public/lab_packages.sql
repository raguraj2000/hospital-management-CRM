-- ==============================================================================
-- Table: public.lab_packages
-- Purpose: Bundled laboratory test packages offered at a package price
-- Source: apps/api/src/db/schema.ts (lab_package), FR-LAB-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    name VARCHAR(120) NOT NULL,
    price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
    test_ids JSONB NOT NULL, -- Array of public.lab_tests.id
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

COMMENT ON TABLE public.lab_packages IS 'Bundled multi-test diagnostic packages (e.g. Fever Profile)';
