-- ==============================================================================
-- Table: public.region_inventory
-- Purpose: Many-to-Many junction associating inventory locations with regions
-- Source: db-design.md Section 6 (Region-to-inventory mapping)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.region_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    region_id BIGINT NOT NULL,
    inventory_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Composite foreign keys enforcing enterprise integrity (region and inventory must share same organization)
    CONSTRAINT fk_reg_inv_region FOREIGN KEY (region_id, company_id) 
        REFERENCES public.regions(id, company_id) ON DELETE CASCADE,
    CONSTRAINT fk_reg_inv_inventory FOREIGN KEY (inventory_id, company_id) 
        REFERENCES public.inventory_locations(id, company_id) ON DELETE RESTRICT,

    CONSTRAINT uq_region_inventory UNIQUE (region_id, inventory_id)
);

CREATE INDEX IF NOT EXISTS ix_region_inv_lookup ON public.region_inventory (inventory_id, region_id) WHERE is_active = true;

-- Explicit hierarchical composite indexes requested for regional and inventory scoping
CREATE INDEX IF NOT EXISTS ix_region_inventory_company_region 
    ON public.region_inventory (company_id, region_id);

CREATE INDEX IF NOT EXISTS ix_region_inventory_company_region_inventory 
    ON public.region_inventory (company_id, region_id, inventory_id);

COMMENT ON TABLE public.region_inventory IS 'Many-to-many junction allowing an inventory location to serve multiple regions without stock duplication';
