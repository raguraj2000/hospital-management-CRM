-- ==============================================================================
-- Table: public.treatment_doses
-- Purpose: Scheduled in-hospital medication doses administered by nursing personnel
-- Source: apps/api/src/db/schema.ts (treatment_dose), FR-RX-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.treatment_doses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    prescription_item_id BIGINT NOT NULL REFERENCES public.prescription_items(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    due_date DATE NOT NULL,
    slot_no INTEGER NOT NULL, -- 1 = Morning, 2 = Afternoon, 3 = Night
    slot VARCHAR(30) NOT NULL,
    amount VARCHAR(30) NULL,
    given_at TIMESTAMPTZ NULL,
    given_by BIGINT NULL REFERENCES global.users(id),
    note TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_treatment_dose UNIQUE (prescription_item_id, due_date, slot_no)
);

CREATE INDEX IF NOT EXISTS ix_treatment_doses_queue ON public.treatment_doses (branch_id, due_date, slot_no) WHERE given_at IS NULL;
COMMENT ON TABLE public.treatment_doses IS 'Nurse administration queue for in-hospital injections, IV drips, and nebulizations';
