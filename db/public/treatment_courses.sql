-- ==============================================================================
-- Table: public.treatment_courses
-- Purpose: Multi-day ambulatory clinical care plans across multiple recurring sittings
-- Source: apps/api/src/db/schema.ts (treatment_course), FR-CRS-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.treatment_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE RESTRICT, -- Initializing visit
    name VARCHAR(120) NOT NULL, -- E.g. 'Dengue 3-Day IV Protocol'
    pay_mode VARCHAR(20) NOT NULL DEFAULT 'per_sitting' CHECK (pay_mode IN ('per_sitting', 'day_one')),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'frozen', 'closed')),
    doctor_user_id BIGINT NULL REFERENCES global.users(id),
    frozen_at TIMESTAMPTZ NULL,
    closed_at TIMESTAMPTZ NULL,
    closed_reason TEXT NULL,
    closed_by BIGINT NULL REFERENCES global.users(id),
    credit_paise BIGINT NOT NULL DEFAULT 0 CHECK (credit_paise >= 0), -- Refundable patient credit if course closes
    start_day DATE NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_courses_patient ON public.treatment_courses (branch_id, patient_id, status);
COMMENT ON TABLE public.treatment_courses IS 'Ambulatory treatment courses coordinating recurring sittings over days';
