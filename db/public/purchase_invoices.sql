-- ==============================================================================
-- Table: public.purchase_invoices
-- Purpose: Inward vendor invoices restocking inventory with complete GST tax breakdown
-- Source: apps/api/src/db/schema.ts (purchase_bill), db-design.md Section 9
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.purchase_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    inventory_id BIGINT NOT NULL REFERENCES public.inventory_locations(id) ON DELETE RESTRICT,
    vendor_id BIGINT NOT NULL REFERENCES public.vendors(id) ON DELETE RESTRICT,
    vendor_invoice_no VARCHAR(60) NOT NULL,
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    
    -- Financials in paise
    taxable_amount_paise BIGINT NOT NULL CHECK (taxable_amount_paise >= 0),
    cgst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (cgst_amount_paise >= 0),
    sgst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (sgst_amount_paise >= 0),
    igst_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (igst_amount_paise >= 0),
    cess_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (cess_amount_paise >= 0),
    total_tax_paise BIGINT NOT NULL DEFAULT 0 CHECK (total_tax_paise >= 0),
    round_off_paise INTEGER NOT NULL DEFAULT 0,
    total_paise BIGINT NOT NULL CHECK (total_paise >= 0),
    paid_paise BIGINT NOT NULL DEFAULT 0 CHECK (paid_paise >= 0),
    
    notes TEXT NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    cancelled_at TIMESTAMPTZ NULL,
    cancel_reason TEXT NULL,
    cancelled_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_purchase_due_date CHECK (due_date >= invoice_date)
);

CREATE INDEX IF NOT EXISTS ix_purchase_inv_vendor ON public.purchase_invoices (vendor_id, invoice_date DESC);
CREATE INDEX IF NOT EXISTS ix_purchase_inv_due ON public.purchase_invoices (branch_id, due_date) WHERE cancelled_at IS NULL;
COMMENT ON TABLE public.purchase_invoices IS 'Supplier purchase invoices capturing inventory inward deliveries and input tax credit';
