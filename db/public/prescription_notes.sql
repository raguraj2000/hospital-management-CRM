-- ==============================================================================
-- Table: public.prescription_notes
-- Purpose: Non-billable physician instructions positioned between prescription lines
-- Source: apps/api/src/db/schema.ts (prescription_note)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.prescription_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('note', 'instruction')),
    text TEXT NOT NULL,
    after_item_id BIGINT NULL REFERENCES public.prescription_items(id) ON DELETE SET NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_rx_notes_visit ON public.prescription_notes (visit_id);
COMMENT ON TABLE public.prescription_notes IS 'Interleaved clinical instructions and dietary guidance on prescriptions';
