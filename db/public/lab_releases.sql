-- Source: apps/api/src/db/schema.ts (lab_release), FR-LAB-03
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    released_by BIGINT NOT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_lab_release_visit ON public.lab_releases (visit_id);
COMMENT ON TABLE public.lab_releases IS 'Audit record of administrative report print release overrides prior to bill payment';
