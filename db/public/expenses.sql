-- ==============================================================================
-- Table: public.expenses
-- Purpose: Non-pharmaceutical hospital operational expenses (stationery, repairs, utility)
-- Source: apps/api/src/db/schema.ts (expense)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    expense_date DATE NOT NULL,
    description VARCHAR(200) NOT NULL,
    vendor_id BIGINT NULL REFERENCES public.vendors(id) ON DELETE SET NULL,
    vendor_name VARCHAR(150) NULL, -- For ad-hoc walk-in vendors
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    mode VARCHAR(20) NOT NULL REFERENCES master.payment_methods(code) DEFAULT 'cash',
    notes TEXT NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_expenses_branch_day ON public.expenses (branch_id, expense_date DESC) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.expenses IS 'General clinic overhead and operational expenditures';
