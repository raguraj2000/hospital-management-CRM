-- ==============================================================================
-- Table: public.inventory_movements
-- Purpose: Immutable stock transaction ledger (Receipts, Dispenses, Transfers, Adjustments)
-- Source: db-design.md Section 7, 10
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    inventory_id BIGINT NOT NULL REFERENCES public.inventory_locations(id) ON DELETE RESTRICT,
    medicine_id BIGINT NOT NULL REFERENCES public.medicines(id) ON DELETE RESTRICT,
    batch_id BIGINT NOT NULL REFERENCES public.inventory_batches(id) ON DELETE RESTRICT,
    movement_type VARCHAR(30) NOT NULL CHECK (movement_type IN ('PURCHASE_RECEIPT', 'SALE_DISPENSE', 'TRANSFER_IN', 'TRANSFER_OUT', 'ADJUSTMENT_ADD', 'ADJUSTMENT_SUB', 'RETURN_VENDOR', 'DISCARD_EXPIRED')),
    quantity_delta INTEGER NOT NULL, -- Positive for stock additions, negative for reductions
    balance_after INTEGER NOT NULL CHECK (balance_after >= 0),
    reference_type VARCHAR(40) NULL, -- 'purchase_invoice', 'pharmacy_sale', 'internal_transfer'
    reference_id BIGINT NULL,
    reason TEXT NULL,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_inv_movements_batch ON public.inventory_movements (batch_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_inv_movements_loc ON public.inventory_movements (inventory_id, created_at DESC);
COMMENT ON TABLE public.inventory_movements IS 'Immutable audit ledger of every inventory stock quantity adjustment';
