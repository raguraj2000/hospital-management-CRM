-- ==============================================================================
-- Table: public.pharmacy_sale_lines
-- Purpose: Specific batch allocations and financial itemization for pharmacy sales
-- Source: apps/api/src/db/schema.ts (pharmacy_sale_line), FR-PHM-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.pharmacy_sale_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES public.pharmacy_sales(id) ON DELETE CASCADE,
    prescription_item_id BIGINT NULL REFERENCES public.prescription_items(id) ON DELETE SET NULL,
    medicine_id BIGINT NOT NULL REFERENCES public.medicines(id) ON DELETE RESTRICT,
    batch_id BIGINT NOT NULL REFERENCES public.inventory_batches(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_paise BIGINT NOT NULL CHECK (unit_price_paise >= 0),
    amount_paise BIGINT NOT NULL CHECK (amount_paise >= 0)
);

CREATE INDEX IF NOT EXISTS ix_sale_lines_sale ON public.pharmacy_sale_lines (sale_id);
COMMENT ON TABLE public.pharmacy_sale_lines IS 'Individual medicine batch allocations supporting FEFO dispensing audit';
