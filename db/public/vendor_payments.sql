-- ==============================================================================
-- Table: public.vendor_payments
-- Purpose: Disbursements made to distributors against purchase invoices
-- Source: apps/api/src/db/schema.ts (vendor_payment)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.vendor_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    purchase_invoice_id BIGINT NOT NULL REFERENCES public.purchase_invoices(id) ON DELETE RESTRICT,
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    mode VARCHAR(20) NOT NULL REFERENCES master.payment_methods(code),
    reference VARCHAR(80) NULL, -- Bank UTR, NEFT reference, or Cheque number
    paid_by BIGINT NULL REFERENCES global.users(id),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_vendor_payments_inv ON public.vendor_payments (purchase_invoice_id);
COMMENT ON TABLE public.vendor_payments IS 'Outward disbursements to suppliers settling purchase bills';
