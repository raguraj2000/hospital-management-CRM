-- ==============================================================================
-- Table: public.visit_charges
-- Purpose: Staging table for minor clinical procedures added to a visit before invoice creation
-- Source: apps/api/src/db/schema.ts (visit_charge), FR-BIL-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.visit_charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE CASCADE,
    description VARCHAR(150) NOT NULL,
    amount_paise BIGINT NOT NULL CHECK (amount_paise >= 0),
    invoice_id BIGINT NULL REFERENCES public.invoices(id) ON DELETE SET NULL, -- Null while unbilled
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_visit_charges_visit ON public.visit_charges (visit_id) WHERE deleted_at IS NULL;
COMMENT ON TABLE public.visit_charges IS 'Procedural charges (dressing, IV set, nebulizer) attached to a visit prior to billing';
