-- ==============================================================================
-- Table: public.lab_orders
-- Purpose: Diagnostic test orders linked to outpatient clinical encounters
-- Source: apps/api/src/db/schema.ts (lab_order), FR-LAB-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.lab_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES public.op_visits(id) ON DELETE RESTRICT,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE RESTRICT,
    test_id BIGINT NOT NULL REFERENCES public.lab_tests(id) ON DELETE RESTRICT,
    price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ordered' 
        CHECK (status IN ('ordered', 'sample_collected', 'completed', 'cancelled')),
    ordered_by BIGINT NULL REFERENCES global.users(id),
    sample_collected_at TIMESTAMPTZ NULL,
    completed_at TIMESTAMPTZ NULL,
    completed_by BIGINT NULL REFERENCES global.users(id),
    corrected_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_lab_orders_queue ON public.lab_orders (branch_id, status);
CREATE INDEX IF NOT EXISTS ix_lab_orders_visit ON public.lab_orders (visit_id);
COMMENT ON TABLE public.lab_orders IS 'Diagnostic investigations ordered for a patient encounter';
