-- ==============================================================================
-- Table: public.pharmacy_sales
-- Purpose: Transaction headers for fulfilled prescriptions and OTC walk-in pharmacy sales
-- Source: apps/api/src/db/schema.ts (pharmacy_sale), FR-PHM-02
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.pharmacy_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    branch_id BIGINT NOT NULL REFERENCES public.branches(id) ON DELETE RESTRICT,
    inventory_id BIGINT NOT NULL REFERENCES public.inventory_locations(id) ON DELETE RESTRICT,
    sale_no VARCHAR(40) NOT NULL, -- E.g. 'PH-261024-001'
    visit_id BIGINT NULL REFERENCES public.op_visits(id) ON DELETE SET NULL, -- Null for OTC direct sales
    patient_id BIGINT NULL REFERENCES public.patients(id) ON DELETE SET NULL,
    total_paise BIGINT NOT NULL CHECK (total_paise >= 0),
    round_off_paise INTEGER NOT NULL DEFAULT 0,
    payment_mode VARCHAR(20) NOT NULL REFERENCES master.payment_methods(code),
    is_direct_otc BOOLEAN NOT NULL DEFAULT false,
    created_by BIGINT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_sale_branch_no UNIQUE (branch_id, sale_no)
);

CREATE INDEX IF NOT EXISTS ix_pharmacy_sales_day ON public.pharmacy_sales (branch_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_pharmacy_sales_visit ON public.pharmacy_sales (visit_id);
COMMENT ON TABLE public.pharmacy_sales IS 'Completed pharmacy sales transactions for prescription and OTC sales';
