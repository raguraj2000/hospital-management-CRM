-- ==============================================================================
-- Table: public.invoice_tax_lines
-- Purpose: Immutable line-level tax component snapshots (CGST, SGST, IGST)
-- Source: db-design.md Section 9 (Patient Billing Tax Breakdown)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.invoice_tax_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT NOT NULL REFERENCES public.invoice_lines(id) ON DELETE CASCADE,
    tax_component VARCHAR(10) NOT NULL CHECK (tax_component IN ('CGST', 'SGST', 'UTGST', 'IGST', 'CESS')),
    rate_percent NUMERIC(5,2) NOT NULL CHECK (rate_percent >= 0),
    tax_amount_paise BIGINT NOT NULL CHECK (tax_amount_paise >= 0)
);

CREATE INDEX IF NOT EXISTS ix_inv_tax_lines_line ON public.invoice_tax_lines (invoice_line_id);
COMMENT ON TABLE public.invoice_tax_lines IS 'Immutable tax snapshots capturing exact CGST, SGST, UTGST, and IGST component values';
