-- ==============================================================================
-- Table: master.gst_rates
-- Purpose: Statutory effective-dated GST rate schedules
-- Source: db-design.md Section 9 (GST Configuration and calculations)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS master.gst_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_code VARCHAR(20) NOT NULL REFERENCES master.gst_tax_codes(code) ON DELETE RESTRICT,
    valid_from DATE NOT NULL,
    valid_to DATE NULL, -- Null represents open-ended current active rate
    
    -- Component tax percentages (must sum to total_rate)
    cgst_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (cgst_rate >= 0),
    sgst_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (sgst_rate >= 0),
    igst_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (igst_rate >= 0),
    cess_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (cess_rate >= 0),
    total_rate NUMERIC(5,2) NOT NULL CHECK (total_rate >= 0),
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_gst_rate_split CHECK (
        (cgst_rate + sgst_rate = igst_rate) OR (igst_rate = 0 AND total_rate = 0)
    ),
    CONSTRAINT chk_gst_valid_range CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX IF NOT EXISTS ix_gst_rates_lookup ON master.gst_rates (tax_code, valid_from, valid_to);
COMMENT ON TABLE master.gst_rates IS 'Effective-dated GST rate definitions preventing historical recalculation when tax rates change';
