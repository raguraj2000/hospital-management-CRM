-- ==============================================================================
-- Table: global.organization_plans
-- Purpose: Commercial SaaS plan tiers and resource quota templates
-- Source: BRD Section 1.2, FR-SEC-01
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.organization_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT NULL,
    default_yearly_fee_paise BIGINT NOT NULL DEFAULT 0,
    max_branches INTEGER NULL,
    max_staff INTEGER NULL,
    features JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE global.organization_plans IS 'Commercial subscription plan catalog defining feature entitlements and default quotas';
