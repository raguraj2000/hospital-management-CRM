-- ==============================================================================
-- Table: global.roles
-- Purpose: Role definitions, both system-wide templates and organization custom roles
-- Source: packages/core/src/db/schema.ts (role), db-design.md Section 8
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    key VARCHAR(60) NOT NULL,   -- E.g. 'doctor', 'visiting_doctor', 'pharmacist', 'nurse'
    name VARCHAR(120) NOT NULL, -- Display title
    description TEXT NULL,
    is_system BOOLEAN NOT NULL DEFAULT false, -- True for core platform default templates
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_role_org_key UNIQUE (company_id, key)
);

CREATE INDEX IF NOT EXISTS ix_roles_org ON global.roles (company_id);
COMMENT ON TABLE global.roles IS 'Role definitions aggregating permissions. company_id is null for global built-in templates';
