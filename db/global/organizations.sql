-- ==============================================================================
-- Table: global.organizations
-- Purpose: Primary multi-tenant customer entity (Hospital enterprise or clinic group)
-- Source: FRD Section 3.1, packages/core/src/db/schema.ts (organization)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    code_prefix VARCHAR(10) NOT NULL DEFAULT '', -- Used for enterprise-wide UHID prefix (e.g. 'AH')
    is_active BOOLEAN NOT NULL DEFAULT true,      -- Suspends access across all branches when false
    plan_name VARCHAR(60) NULL,
    yearly_fee_paise BIGINT NOT NULL DEFAULT 0,  -- Annual licensing fee in whole paise
    paid_until DATE NULL,                        -- Subscription expiry date
    grace_days INTEGER NOT NULL DEFAULT 7,       -- Days of continued access after expiry
    max_branches INTEGER NULL,                   -- Quota on physical branches (null = unlimited)
    max_staff INTEGER NULL,                      -- Quota on active staff accounts (null = unlimited)
    modules_off JSONB NOT NULL DEFAULT '[]'::jsonb, -- Array of disabled module keys (e.g. ["lab", "courses"])
    support_until TIMESTAMPTZ NULL,              -- Temporary read-only vendor support access window
    delete_on DATE NULL,                         -- Scheduled offboarding purge date
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,

    CONSTRAINT chk_org_code_prefix CHECK (code_prefix ~ '^[A-Z0-9]*$'),
    CONSTRAINT chk_org_grace_days CHECK (grace_days >= 0),
    CONSTRAINT chk_org_fee_paise CHECK (yearly_fee_paise >= 0)
);

COMMENT ON TABLE global.organizations IS 'Tenant customer organizations operating clinics or hospitals on the platform';
COMMENT ON COLUMN global.organizations.code_prefix IS 'Prefix prepended to generated Unique Health IDs (e.g., AH -> AH000001)';
COMMENT ON COLUMN global.organizations.modules_off IS 'JSON array of module keys disabled at enterprise level';
