-- ==============================================================================
-- Table: global.platform_payments
-- Purpose: Licensing fees paid by tenant organizations to the platform provider
-- Source: packages/core/src/db/schema.ts (platform_payment)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.platform_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE RESTRICT,
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    paid_on DATE NOT NULL,
    period_from DATE NOT NULL,
    period_to DATE NOT NULL,
    note TEXT NULL,
    created_by BIGINT NULL, -- References global.users(id), deferred foreign key
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_platform_payment_period CHECK (period_to >= period_from)
);

CREATE INDEX IF NOT EXISTS ix_platform_payment_org ON global.platform_payments (company_id, paid_on DESC);
COMMENT ON TABLE global.platform_payments IS 'Ledger of software licensing payments made by tenant hospitals to SaaS platform';
