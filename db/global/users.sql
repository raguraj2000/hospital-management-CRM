-- ==============================================================================

CREATE TABLE IF NOT EXISTS global.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile VARCHAR(20) NOT NULL UNIQUE,          -- Primary Indian login mobile (+91XXXXXXXXXX)
    username CITEXT NOT NULL UNIQUE,             -- Case-insensitive handle
    name VARCHAR(150) NOT NULL,                  -- Full legal staff name
    password_hash VARCHAR(255) NOT NULL,         -- Scrypt encoded password hash
    is_platform_admin BOOLEAN NOT NULL DEFAULT false, -- Super-admin; manages organizations, zero clinical access
    is_active BOOLEAN NOT NULL DEFAULT true,     -- Deactivation flag
    failed_logins INTEGER NOT NULL DEFAULT 0,    -- Consecutive failed attempts
    locked_until TIMESTAMPTZ NULL,               -- Lockout expiry timestamp
    last_login_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_user_mobile_format CHECK (mobile ~ '^\+91[6-9][0-9]{9}$')
);

CREATE INDEX IF NOT EXISTS ix_users_active_mobile ON global.users (mobile) WHERE is_active = true;
COMMENT ON TABLE global.users IS 'Global identity and authentication credentials for all healthcare personnel and administrators';
