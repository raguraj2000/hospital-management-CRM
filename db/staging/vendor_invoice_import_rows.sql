-- ==============================================================================
-- Table: staging.vendor_invoice_import_rows
-- Purpose: Staged line items from vendor invoices with pack multipliers and free quantities
-- Source: packages/shared/src/purchase-import.ts
-- ==============================================================================

CREATE TABLE IF NOT EXISTS staging.vendor_invoice_import_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id BIGINT NOT NULL REFERENCES staging.vendor_invoice_imports(id) ON DELETE CASCADE,
    row_index INTEGER NOT NULL,
    raw_medicine_name VARCHAR(150) NOT NULL,
    resolved_medicine_id BIGINT NULL REFERENCES public.medicines(id),
    batch_no VARCHAR(50) NOT NULL,
    expiry_date DATE NOT NULL,
    pack_size INTEGER NOT NULL DEFAULT 1,
    pack_qty INTEGER NOT NULL,
    free_qty INTEGER NOT NULL DEFAULT 0,
    rate_paise BIGINT NOT NULL,
    gst_percent NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    is_valid BOOLEAN NOT NULL DEFAULT false,
    error_message TEXT NULL
);

COMMENT ON TABLE staging.vendor_invoice_import_rows IS 'Raw staged lines of imported vendor bills awaiting confirmation and promotion to public stock';
