-- ==============================================================================
-- Table: staging.inventory_import_rows
-- Purpose: Individual rows parsed from an inventory import spreadsheet with validation errors
-- Source: db-design.md Section 5 (Schema D: staging)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS staging.inventory_import_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES staging.inventory_import_batches(id) ON DELETE CASCADE,
    row_number INTEGER NOT NULL,
    raw_data JSONB NOT NULL,
    medicine_name VARCHAR(150) NULL,
    batch_no VARCHAR(50) NULL,
    expiry_date VARCHAR(20) NULL,
    quantity INTEGER NULL,
    price_rupees NUMERIC(10,2) NULL,
    is_valid BOOLEAN NOT NULL DEFAULT false,
    validation_errors JSONB NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_import_rows_batch ON staging.inventory_import_rows (batch_id, is_valid);
COMMENT ON TABLE staging.inventory_import_rows IS 'Staged spreadsheet rows with validation status prior to transactional promotion';
