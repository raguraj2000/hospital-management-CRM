-- ==============================================================================
-- Table: staging.inventory_import_batches
-- Purpose: Spreadsheet upload headers for batch inventory onboarding
-- Source: db-design.md Section 5 (Schema D: staging)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS staging.inventory_import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES global.organizations(id) ON DELETE CASCADE,
    inventory_id BIGINT NOT NULL REFERENCES public.inventory_locations(id) ON DELETE RESTRICT,
    filename VARCHAR(255) NOT NULL,
    total_rows INTEGER NOT NULL DEFAULT 0,
    valid_rows INTEGER NOT NULL DEFAULT 0,
    error_rows INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'UPLOADED' 
        CHECK (status IN ('UPLOADED', 'PARSING', 'VALIDATED', 'PROMOTED', 'FAILED')),
    uploaded_by BIGINT NOT NULL REFERENCES global.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ NULL
);

COMMENT ON TABLE staging.inventory_import_batches IS 'Batch upload sessions for bulk medicine stock and catalog imports';
