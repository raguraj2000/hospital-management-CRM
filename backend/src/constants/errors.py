"""Application error codes matching legacy frontend error contract."""

from enum import StrEnum


class ErrorCode(StrEnum):
    # Standard HTTP / Validation
    BAD_REQUEST = "BAD_REQUEST"
    VALIDATION_ERROR = "VALIDATION_ERROR"
    NOT_FOUND = "NOT_FOUND"
    CONFLICT = "CONFLICT"
    UNAUTHORIZED = "UNAUTHORIZED"
    FORBIDDEN = "FORBIDDEN"
    INTERNAL_SERVER_ERROR = "INTERNAL_SERVER_ERROR"

    # Business Invariants
    TENANT_MISMATCH = "TENANT_MISMATCH"
    INVALID_BRANCH = "INVALID_BRANCH"
    BRANCH_LOCKED = "BRANCH_LOCKED"
    INVALID_STATUS_TRANSITION = "INVALID_STATUS_TRANSITION"
    
    # Financial & GST
    INSUFFICIENT_STOCK = "INSUFFICIENT_STOCK"
    INVOICE_ALREADY_POSTED = "INVOICE_ALREADY_POSTED"
    INVOICE_IMMUTABLE = "INVOICE_IMMUTABLE"
    NEGATIVE_AMOUNT_NOT_ALLOWED = "NEGATIVE_AMOUNT_NOT_ALLOWED"
    
    # Clinical
    VISIT_NOT_ACTIVE = "VISIT_NOT_ACTIVE"
    DOCTOR_NOT_ROSTERED = "DOCTOR_NOT_ROSTERED"
    EMR_LOCKED = "EMR_LOCKED"

